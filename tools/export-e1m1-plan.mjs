#!/usr/bin/env node
/**
 * Development-only survey of the E1M1 reference layout.
 * This tool reads geometry and object placements, never images, audio or BSP.
 * The generated plan is committed as readable construction parameters; neither
 * this exporter nor its input file is needed to build or run the game.
 *
 * node tools/export-e1m1-plan.mjs [reference/doom1.wad] [src/e1m1-plan.js]
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';

const input = process.argv[2] || fileURLToPath(new URL('../reference/doom1.wad', import.meta.url));
const output = process.argv[3] || fileURLToPath(new URL('../src/e1m1-plan.js', import.meta.url));
const bytes = readFileSync(input);
const expected = '1d7d43be501e67d927e415e0b8f3e29c3bf33075e859721816f652a526cac771';
if (createHash('sha256').update(bytes).digest('hex') !== expected) throw new Error('Unexpected reference edition; refusing to change the surveyed layout.');
const directory = bytes.readInt32LE(8), count = bytes.readInt32LE(4);
const name = (buffer, offset) => buffer.toString('ascii', offset, offset + 8).split('\0')[0];
let marker = -1;
const lumps = new Map();
for (let i = 0; i < count; i++) {
  const at = directory + i * 16, label = name(bytes, at + 8);
  if (label === 'E1M1') { marker = i; continue; }
  if (marker < 0) continue;
  if (/^E\dM\d$/.test(label)) break;
  if (!['VERTEXES', 'LINEDEFS', 'SIDEDEFS', 'SECTORS', 'THINGS'].includes(label)) continue;
  const start = bytes.readInt32LE(at), length = bytes.readInt32LE(at + 4);
  lumps.set(label, bytes.subarray(start, start + length));
}
function records(label, stride, decode) {
  const data = lumps.get(label);
  if (!data || data.length % stride) throw new Error(`Invalid geometry table: ${label}`);
  return Array.from({length: data.length / stride}, (_, i) => decode(data, i * stride));
}
const side = index => index === 65535 ? -1 : index;
const originalVertices = records('VERTEXES', 4, (b, i) => [b.readInt16LE(i), b.readInt16LE(i + 2)]);
const walls = records('LINEDEFS', 14, (b, i) => [b.readUInt16LE(i), b.readUInt16LE(i + 2), b.readUInt16LE(i + 4), b.readUInt16LE(i + 6), b.readUInt16LE(i + 8), side(b.readUInt16LE(i + 10)), side(b.readUInt16LE(i + 12))]);
const usedVertices = [...new Set(walls.flatMap(row => row.slice(0, 2)))].sort((a, b) => a - b);
const vertexIds = new Map(usedVertices.map((old, id) => [old, id]));
const vertices = usedVertices.map(id => originalVertices[id]);
for (const wall of walls) { wall[0] = vertexIds.get(wall[0]); wall[1] = vertexIds.get(wall[1]); }
const faces = records('SIDEDEFS', 30, (b, i) => [b.readInt16LE(i), b.readInt16LE(i + 2), name(b, i + 4), name(b, i + 12), name(b, i + 20), b.readUInt16LE(i + 28)]);
const sectors = records('SECTORS', 26, (b, i) => [b.readInt16LE(i), b.readInt16LE(i + 2), name(b, i + 4), name(b, i + 12), b.readInt16LE(i + 20), b.readUInt16LE(i + 22), b.readUInt16LE(i + 24)]);
const objects = records('THINGS', 10, (b, i) => [b.readInt16LE(i), b.readInt16LE(i + 2), b.readUInt16LE(i + 4), b.readUInt16LE(i + 6), b.readUInt16LE(i + 8)]);
const section = (label, schema, rows) => `  // ${schema}\n  ${label}: [\n${rows.map((row, id) => `    ${JSON.stringify(row)}, // ${id}`).join('\n')}\n  ],\n`;
const header = `/**
 * E1M1 Hangar: fixed reference layout, expressed as construction parameters.
 * Coordinates are classic map units; array indices preserve mechanism IDs.
 * Surface names are recipe identifiers only: no palette, patch, texture pixels,
 * sprite, sound, original BSP, triangulation or encoded binary is stored here.
 * Runtime floors and spatial queries are generated by procedural-map.js.
 * Re-survey with tools/export-e1m1-plan.mjs; normal builds need no reference file.
 */
const freeze = value => {
  if (value && typeof value === 'object') {
    for (const item of Object.values(value)) freeze(item);
    Object.freeze(value);
  }
  return value;
};

export const E1M1_PLAN = freeze({
  name: 'E1M1',
  title: 'Hangar',
  version: 1,
`;
writeFileSync(output, header
  + section('vertices', 'x, y; only wall endpoints, no reference BSP split vertices', vertices)
  + section('walls', 'start vertex, end vertex, flags, action, tag, right face, left face', walls)
  + section('faces', 'horizontal offset, vertical offset, upper recipe, lower recipe, middle recipe, sector', faces)
  + section('sectors', 'floor height, ceiling height, floor recipe, ceiling recipe, light, effect, tag', sectors)
  + section('objects', 'x, y, angle in degrees, archetype, difficulty/placement flags', objects)
  + '});\n\nexport default E1M1_PLAN;\n');
console.log(`Surveyed ${vertices.length} wall endpoints, ${walls.length} walls, ${sectors.length} sectors and ${objects.length} placements. No media or BSP exported.`);
